// Compile only template geometry. No renderer, screenshots, model call or raster assets.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { DOMParser } from '@xmldom/xmldom';
const source = new URL('../third_party/ppt-master/presentation_core/', import.meta.url), templates = {};
for (const name of (await readdir(source)).filter(n => n.endsWith('.svg')).sort()) {
  const doc = new DOMParser().parseFromString(await readFile(new URL(name, source), 'utf8'), 'application/xml');
  const slots = {};
  for (const n of [...doc.getElementsByTagName('g')]) {
    const bounds = n.getAttribute('data-pptx-bounds'); if (!bounds) continue;
    const [x, y, w, h] = bounds.split(' ').map(v => Number(v) / 96);
    slots[n.getAttribute('id').replace(/-slot$/, '')] = { x, y, w, h };
  }
  const panels = [...doc.getElementsByTagName('rect')].filter(n => n.getAttribute('id') !== 'master-background').map(n => Object.fromEntries(['x', 'y', 'width', 'height'].map((a, i) => [['x', 'y', 'w', 'h'][i], +n.getAttribute(a) / 96])));
  templates[doc.documentElement.getAttribute('data-pptx-layout')] = { file: name, slots, panels };
}
await writeFile(new URL('../public/core-templates.js', import.meta.url), `// Generated by scripts/import-core-templates.js from ppt-master (MIT), pinned b113d23720260c411ee47b2b05a73615f954deeb.\n// Copyright (c) 2025-2026 Hugo He. Full license: third_party/ppt-master/LICENSE.\nexport const coreTemplates = ${JSON.stringify(templates, null, 2)};\n`);
console.log(`Compiled ${Object.keys(templates).length} native layout geometries.`);
